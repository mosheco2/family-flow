async function seedQuestLibrary() {
  console.log('🌱 מתחיל seed של ספריית קווסטים...\n');

  let questCount = 0;
  let questionCount = 0;

  for (const q of QUESTS) {
    try {
      // הכנס קווסט
      const result = await pool.query(`
        INSERT INTO quest_library
          (title, subject, description, age_min, age_max,
           difficulty, flw_reward, pass_score,
           visibility, tags, is_featured)
        VALUES ($1,$2,$3,$4,$5,$6,$7,$8,'builtin',$9,true)
        ON CONFLICT DO NOTHING
        RETURNING id
      `, [q.title, q.subject, q.description, q.age_min, q.age_max,
          q.difficulty, q.flw_reward, q.pass_score, q.tags]);

      if (!result.rows[0]) {
        console.log(`⚠️  קווסט קיים: "${q.title}"`);
        continue;
      }

      const questId = result.rows[0].id;
      questCount++;

      // הכנס שאלות
      for (let i = 0; i < q.questions.length; i++) {
        const qq = q.questions[i];
        const options = qq.opts ? JSON.stringify(qq.opts) : null;

        await pool.query(`
          INSERT INTO quest_library_questions
            (quest_id, question_text, answer_type,
             correct_answer, options_json, explanation, order_index)
          VALUES ($1,$2,$3,$4,$5,$6,$7)
        `, [questId, qq.q, qq.type || 'multiple_choice',
            qq.correct, options, qq.ex || '', i]);

        questionCount++;
      }

      console.log(`✅ "${q.title}" — ${q.questions.length} שאלות`);

    } catch (err) {
      console.error(`❌ שגיאה ב-"${q.title}":`, err.message);
    }
  }

  console.log(`\n🎉 סיום! נוספו ${questCount} קווסטים ו-${questionCount} שאלות.`);
  await pool.end();
}

seedQuestLibrary().catch(err => {
  console.error('שגיאה כללית:', err);
  process.exit(1);
});
